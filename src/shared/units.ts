import { currentLanguage } from '../i18n';
import { decimal } from './format';

/**
 * Количество со своей единицей: «10 мешков», «6 бутылок», «1 лист».
 *
 * Единицу продавец пишет свободным текстом, и склонять её вслепую нельзя:
 * «10 мешок» читается ошибкой, а «10 мешк-ов», собранное по правилу, — ещё
 * хуже. Поэтому склоняются только знакомые единицы — те, что встречаются
 * у продавцов витрины, — а незнакомая и сокращённая («шт.», «кг», «м²»)
 * ставится как есть: сокращение не склоняется и по-русски. Только «шт»
 * получает точку (`unitLabel`) — чтобы «2 шт.» не стояло рядом с «2 шт».
 *
 * Склонение — только для русского. В казахском после числа существительное
 * стоит в единственном числе, а английских единиц продавцы не пишут.
 */
const FORMS: Record<string, [string, string, string]> = {
  мешок: ['мешок', 'мешка', 'мешков'],
  лист: ['лист', 'листа', 'листов'],
  ведро: ['ведро', 'ведра', 'вёдер'],
  упаковка: ['упаковка', 'упаковки', 'упаковок'],
  коробка: ['коробка', 'коробки', 'коробок'],
  ящик: ['ящик', 'ящика', 'ящиков'],
  бутылка: ['бутылка', 'бутылки', 'бутылок'],
  лоток: ['лоток', 'лотка', 'лотков'],
  канистра: ['канистра', 'канистры', 'канистр'],
  пачка: ['пачка', 'пачки', 'пачек'],
  банка: ['банка', 'банки', 'банок'],
  рулон: ['рулон', 'рулона', 'рулонов'],
  пара: ['пара', 'пары', 'пар'],
  штука: ['штука', 'штуки', 'штук'],
  блок: ['блок', 'блока', 'блоков'],
  поддон: ['поддон', 'поддона', 'поддонов'],
  комплект: ['комплект', 'комплекта', 'комплектов'],
  метр: ['метр', 'метра', 'метров'],
  литр: ['литр', 'литра', 'литров'],
  килограмм: ['килограмм', 'килограмма', 'килограммов'],
  тонна: ['тонна', 'тонны', 'тонн'],
  // Опт одежды: «80 000 за линейку», «2 пресса».
  линейка: ['линейка', 'линейки', 'линеек'],
  пресс: ['пресс', 'пресса', 'прессов'],
  паллета: ['паллета', 'паллеты', 'паллет'],
};

/** Форма по числу: 1 мешок, 2 мешка, 5 мешков; дробное — «2,5 мешка». */
function formOf(amount: number, forms: [string, string, string]): string {
  if (!Number.isInteger(amount)) return forms[1];
  const last = amount % 10;
  const lastTwo = amount % 100;
  if (last === 1 && lastTwo !== 11) return forms[0];
  if (last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14)) return forms[1];
  return forms[2];
}

/** «10 мешков» — число записью выбранного языка, единица по-русски склонённая. */
export function quantityWithUnit(amount: number, unit: string): string {
  const forms = currentLanguage() === 'ru' ? FORMS[unit.trim().toLowerCase()] : undefined;
  return `${decimal(amount)} ${forms ? formOf(amount, forms) : unitLabel(unit)}`;
}

/**
 * Единица рядом с числом, стоящим отдельно, — в поле количества: «20» и
 * «мешков в корзине». Знакомая склоняется по числу, как в `quantityWithUnit`;
 * незнакомая и сокращённая — как `unitLabel`.
 */
export function unitFor(amount: number, unit: string): string {
  const forms = currentLanguage() === 'ru' ? FORMS[unit.trim().toLowerCase()] : undefined;
  return forms ? formOf(amount, forms) : unitLabel(unit);
}

/**
 * Единица для подписи рядом с числом: «шт» — с точкой, как пишется
 * сокращение («5 шт. в корзине»). Продавец набирает единицу свободным
 * текстом и точку часто опускает; остальное ставится как есть.
 */
function unitLabel(unit: string): string {
  return unit.trim() === 'шт' ? 'шт.' : unit;
}

/**
 * Единица после «за» — «за упаковку», «за мешок», «за шт.».
 *
 * После «за» русское существительное стоит в винительном падеже: у знакомых
 * единиц женского рода на «-а» окончание меняется на «-у», мужской и средний
 * род неодушевлённых совпадают с именительным. Незнакомая и сокращённая
 * единица — как `unitLabel`: сокращение не склоняется. На казахском и
 * английском склонения нет — как в `unitFor`.
 */
export function unitPer(unit: string): string {
  const key = unit.trim().toLowerCase();
  if (currentLanguage() !== 'ru' || !FORMS[key]) return unitLabel(unit);
  return key.endsWith('а') ? `${key.slice(0, -1)}у` : key;
}
