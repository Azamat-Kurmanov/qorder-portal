import type { ComponentProps } from 'react';
import { cn } from './cn';

/**
 * Карточка: белая поверхность на кремовом основании.
 *
 * Глубина держится на волосяной линии, смене поверхности и самой мягкой
 * из трёх теней — `soft`, то есть «лист лежит на бумаге». Раньше тени
 * не было вовсе, и на большом мониторе карточка сливалась с основанием:
 * разница в четыре процента яркости на просвет не читается.
 *
 * Тень приходит токеном, а не числами в этом классе. Числа по месту и были
 * здесь раньше — вместе с предупреждением, что через месяц они перестанут
 * быть системой. Перестали: стоило поднять при наведении второй элемент,
 * и значений стало два разных. Теперь ступеней три и живут они в `index.css`.
 *
 * При наведении карточка поднимается на две точки и уходит на ступень выше
 * (`lift`). Две точки — это ровно столько, чтобы тень удлинилась заметно,
 * а строка текста не сдвинулась под курсором.
 */
export function Card({ className, interactive = false, ...props }: ComponentProps<'div'> & { interactive?: boolean }) {
  return (
    <div
      className={cn(
        // Край и тень — из шаблона продавца (`qo-card` в index.css): линия,
        // тень или ничего. Без шаблона — прежние линия и мягкая тень.
        'qo-card rounded-[var(--radius-card)] bg-surface',
        interactive
          && 'qo-card-hover transition-all duration-300 ease-out hover:-translate-y-0.5',
        className,
      )}
      {...props}
    />
  );
}
