import { useLayoutEffect, useRef, useState } from 'react';

/**
 * Ширина самого блока, а не окна.
 *
 * Окно не отвечает за то, сколько места у экрана: между ним и содержимым
 * стоит оболочка. На витрине это две её колонки — разделы (232) и корзина
 * (340), — и на планшете в 1024 точки содержимому остаётся 396. Раскладка,
 * выбранная по окну, раскладывалась там в ширину, которой нет: витрина
 * ставила рядом колонку рубрик и три плитки, то есть около девятисот точек
 * в четырёхстах. Ту же колонку меняет и складывание рельса, которого окно
 * не видит вовсе.
 *
 * Отдельно от `useWideScreen`: тот отвечает на другой вопрос — «перестроилась
 * ли ОБОЛОЧКА», — и его порог обязан совпадать с `lg` Tailwind, потому что
 * рельс разделов прячется классом. Один порог на два разных вопроса и был
 * причиной поломки.
 *
 * Ноль до первого измерения — не «узко», а «ещё не знаем», и раскладка по
 * нему выбирается самая безопасная: узкая помещается в любую ширину, широкая
 * не помещается никуда. Первое измерение при этом происходит до отрисовки
 * (`useLayoutEffect`), поэтому мигания раскладкой нет.
 */
export function useColumnWidth<T extends HTMLElement>() {
  const ref = useRef<T | null>(null);
  const [width, setWidth] = useState(0);

  useLayoutEffect(() => {
    const node = ref.current;
    if (!node) return;

    const measure = () => setWidth(node.getBoundingClientRect().width);
    measure();

    // Ширина колонки меняется не только вместе с окном: складывается рельс,
    // появляется и пропадает панель корзины. Слушать окно значило бы
    // пропустить обе перемены.
    const observer = new ResizeObserver(measure);
    observer.observe(node);
    return () => observer.disconnect();
  }, []);

  return [ref, width] as const;
}
