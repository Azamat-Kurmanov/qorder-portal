/**
 * Заполнитель на месте снимка позиции — одна палитра и один выбор на весь кабинет.
 *
 * Единственные сырые цвета в кабинете — и умышленно не токены: токен объявляет
 * смысл («в наличии», «чернила», «акцент»), а здесь смысла нет, это заглушка
 * на месте снимка. Взяты прямо из макета — там все снимки нарисованы такими
 * градиентами.
 *
 * Общим модулем, а не по месту: витрина и корзина с разными палитрами
 * и разными способами выбора рисовали один и тот же цемент без фото разными
 * пятнами, а по пятну человек узнаёт позицию быстрее, чем по названию.
 */
const PLACEHOLDERS: readonly (readonly [string, string])[] = [
  ['#D9D2C6', '#B9AE9C'],
  ['#E7DFCF', '#CBBFA6'],
  ['#DCD3C2', '#A8997F'],
  ['#DED6C8', '#B3A793'],
  ['#D8D8D2', '#A5A59C'],
  ['#E2DACB', '#BDB09A'],
  ['#D5DCD8', '#9FB0A8'],
];

/**
 * Пара цветов градиента для позиции.
 *
 * Выбирается по идентификатору, а не случайно: случайный менялся бы на каждый
 * ответ сервера, и список мигал бы разными пятнами под пальцем.
 */
export function placeholderOf(seed: string): readonly [string, string] {
  let sum = 0;
  for (let index = 0; index < seed.length; index += 1) sum = (sum * 31 + seed.charCodeAt(index)) % 9973;
  return PLACEHOLDERS[sum % PLACEHOLDERS.length];
}
