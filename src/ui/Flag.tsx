import type { Language } from '../i18n';
import { cn } from './cn';

/**
 * Флаги те же, что на странице входа: их показывает переключатель темы
 * Keycloak (`back/qorder/deploy/keycloak/themes/q-order/login/messages/*`,
 * ключи `locale_ru`, `locale_kk`, `locale_en`), и такие же стоят в кабинете
 * сотрудника (`frontend/front/.../ShellMenu.tsx`).
 *
 * Расходиться этим местам нельзя: человек проходит через вход и кабинет
 * подряд, и разные флаги у одного языка читаются как разные языки.
 *
 * Английский помечен британским флагом, а не американским, — тем же, что
 * на входе; и `Intl` в кабинете тоже взят британским (`en-GB`).
 */
const FLAGS: Record<Language, string> = { ru: '🇷🇺', kk: '🇰🇿', en: '🇬🇧' };

/**
 * Флаг страны языка.
 *
 * Флаг именно дополняет подпись, а не заменяет её. Строго говоря флаг — это
 * страна, а не язык: на русском говорят не только в России, и англоязычному
 * не из Великобритании `🇬🇧` про язык ничего не сообщает. Плюс цветных
 * флагов нет в шрифтах Windows и части сборок Linux — там эмодзи вырождается
 * в две буквы. Название языка рядом снимает оба случая, а флаг остаётся тем,
 * ради чего он и нужен: меткой, по которой свою строку находят взглядом,
 * не читая.
 *
 * Помечен `aria-hidden`: язык рядом назван словом, и диктор, прочитав ещё
 * и «флаг Казахстана», сказал бы одно и то же дважды.
 */
export function Flag({ language, className }: { language: Language; className?: string }) {
  return (
    <span
      data-flag={language}
      aria-hidden="true"
      className={cn('shrink-0 text-lead leading-none', className)}
    >
      {FLAGS[language]}
    </span>
  );
}
