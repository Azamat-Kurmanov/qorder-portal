import { useEffect, useRef, useState, type ReactNode } from 'react';
import { cn } from './cn';

/**
 * Упругий толчок на изменившемся числе.
 *
 * Нужен там, где значение меняется НЕ на том месте, куда человек смотрит:
 * счётчик позиций в шапке, итог в панели заявки. Нажали «В корзину» внизу
 * длинной витрины — число наверху изменилось молча, и добросовестный
 * закупщик кладёт ту же позицию второй раз, не поверив, что первая прошла.
 *
 * Толчок происходит только на СМЕНЕ значения и не происходит на первой
 * отрисовке: прыгающие числа на только что открывшемся экране читаются
 * как поломка, а не как ответ на действие.
 *
 * Анимация перезапускается сменой ключа, а не снятием и возвратом класса:
 * класс, снятый и поставленный в одном кадре, браузер считает не менявшимся,
 * и второе подряд добавление проходило бы без толчка — ровно в том случае,
 * ради которого толчок и заведён.
 */
export function Bump({
  value,
  children,
  className,
}: {
  /** Что отслеживается. Сменилось — будет толчок. */
  value: unknown;
  children: ReactNode;
  className?: string;
}) {
  const first = useRef(true);
  const [beat, setBeat] = useState(0);

  useEffect(() => {
    if (first.current) {
      first.current = false;
      return;
    }
    setBeat((count) => count + 1);
  }, [value]);

  return (
    <span key={beat} className={cn('inline-flex', beat > 0 && 'animate-pop', className)}>
      {children}
    </span>
  );
}
