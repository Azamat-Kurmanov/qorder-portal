import { cn } from './cn';

/**
 * Ожидание в форме будущего содержимого.
 *
 * Заглушка повторяет форму того, что придёт: список не прыгает, когда ответ
 * дойдёт, и человек на медленной сети видит, ЧТО именно грузится, а не белый
 * экран. Форму задаёт вызывающий (высота, число колонок) — он один и знает,
 * что здесь встанет.
 *
 * Свет бежит по заглушке слева направо. Это не украшение: мигающий серый
 * прямоугольник, стоявший здесь раньше (`animate-pulse`), читается как
 * «что-то сломалось и моргает», а бегущий свет — как «идёт». На мобильной
 * сети, ради которой заглушка и нужна, разница между этими двумя сообщениями
 * решает, дождётся человек ответа или перезагрузит страницу.
 *
 * Настройку «меньше движения» бег гасит правилом в `index.css`: остаётся
 * ровная поверхность, и это правильно — форма содержимого важнее света.
 */
export function Skeleton({ className, ...props }: React.ComponentProps<'div'>) {
  return (
    <div
      aria-hidden="true"
      className={cn(
        'animate-shimmer rounded-[var(--radius-card)] border border-hairline',
        // Полоса света шириной в четверть — в градиенте, растянутом вдвое
        // шире блока: двигается не элемент, а положение фона, и заглушка
        // не перерисовывает раскладку соседей.
        'bg-[linear-gradient(100deg,var(--color-sunk)_38%,var(--color-surface)_52%,var(--color-sunk)_66%)]',
        'bg-[length:220%_100%]',
        className,
      )}
      {...props}
    />
  );
}
