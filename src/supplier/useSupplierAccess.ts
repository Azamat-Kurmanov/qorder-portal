import { useGetPortalSuppliers } from '../api/generated';
import { useSupplier } from './useSupplier';

/** Открыт ли кабинет поставщиком — и знаем ли мы это уже наверняка. */
export interface SupplierAccess {
  /** Список поставщиков пришёл: до этого ответа судить не о чем. */
  answered: boolean;
  /**
   * У клиента есть хотя бы один поставщик.
   *
   * Пока список не пришёл, считается, что есть: полоса об отсутствии
   * доступа, мигнувшая на долю секунды при каждой загрузке у клиента,
   * с которым всё в порядке, пугает сильнее, чем объясняет.
   */
  activated: boolean;
  /**
   * Кабинет открыт, это подтверждено ответом сервера, и магазин уже выбран из этого списка.
   *
   * По этому признаку включаются запросы оболочки — заявка и уведомления.
   * Уйди они раньше ответа, клиент без поставщика получал бы отказ на каждый:
   * заголовок `X-Supplier-Id` в них уходит из сохранённого выбора, который
   * к этому моменту может указывать в никуда.
   */
  ready: boolean;
}

/**
 * Доступ к кабинету — из списка поставщиков.
 *
 * Отдельным запросом это не спрашивается: список кабинет запрашивает и так,
 * а пустой список и есть ответ «поставщик кабинет не открыл». Хук существует
 * затем, чтобы этот вывод делался в одном месте: разойдись он по компонентам,
 * один из них однажды остался бы с прежним условием и продолжил слать запросы
 * туда, где их ждёт отказ.
 */
export function useSupplierAccess(): SupplierAccess {
  const suppliers = useGetPortalSuppliers();
  const answered = suppliers.data?.status === 200;
  // Ответ сужается по статусу здесь же, а не через переменную: генерация
  // объявляет тело объединением успеха и отказов, и вынесенный признак
  // это объединение не сужает.
  const list = suppliers.data?.status === 200 ? suppliers.data.data : [];
  const activated = !(answered && list.length === 0);

  // Магазин выбирается шагом позже прихода списка (RequireSupplier): без этой проверки
  // оболочка успевала отправить запросы без `X-Supplier-Id` и получала отказы
  // «Поставщик недоступен» — экран каталога в этот момент показывал «Не удалось загрузить».
  const { supplierId } = useSupplier();
  const chosen = supplierId !== null && list.some((supplier) => supplier.supplierId === supplierId);

  return { answered, activated, ready: answered && activated && chosen };
}
