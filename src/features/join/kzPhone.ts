/**
 * Казахстанский номер — под ним текст ошибки `validation.pattern.phone`; контракт пускает любые страны.
 * С кодом (+7, 7, 8) — ещё 10 цифр; без кода — 10 цифр, начиная с 7 (у всех кодов
 * Казахстана): иначе «8701123456» (8 и 9 цифр) проходил бы как полный номер.
 * После кода тоже «7»: иначе «701 123 45 678» читалось бы как +7 011 234 56 78.
 */
export const KZ_PHONE = /^\s*(?:(?:\+7|7|8)[\s()-]*7(?:[\s()-]*\d){9}|7(?:[\s()-]*\d){9})[\s()-]*$/;
