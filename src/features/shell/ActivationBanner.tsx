import { TriangleAlert } from '../../ui/icons';
import { useTranslation } from 'react-i18next';
import { cn } from '../../ui/cn';

/**
 * Полоса поверх кабинета, который поставщик ещё не открыл.
 *
 * Доступ к кабинету даёт поставщик — ссылкой активации. Пока он её не дал,
 * клиенту здесь нечего показывать: витрина, заявка и уведомления принадлежат
 * поставщику, и без него каждый запрос получает отказ. Отказ ничего
 * не объясняет: понять по пустому экрану, что нужно попросить ссылку,
 * невозможно, и человек считает кабинет сломанным.
 *
 * Красным — тем же токеном, которым кабинет говорит об отказах: полоса
 * сообщает не о новости, а о том, что работать здесь пока нельзя. Липкая —
 * потому что объяснение, уехавшее вверх при первой же прокрутке, оставляет
 * человека наедине с тем самым пустым экраном. Не закрывается: закрытая
 * подсказка снимает единственное объяснение, а причина никуда не девается —
 * полоса уходит сама, как только поставщик появится.
 *
 * Стоит под шапкой (68 точек на обеих ширинах), а не поверх неё: имя
 * поставщика и разделы остаются доступны — за ссылкой идут к поставщику,
 * а список поставщиков объясняет, к какому именно.
 */
export function ActivationBanner() {
  const { t } = useTranslation();

  return (
    <div
      role="alert"
      className={cn(
        'sticky top-[68px] z-10 border-b border-gone/25 bg-gone/10 px-4 py-3 lg:px-7',
        // По центру: полоса тянется во всю ширину монитора, и строка,
        // прижатая к левому краю, теряется в пустоте рядом с разделами —
        // читают её взглядом посередине экрана, где стоит и сам кабинет.
        'flex items-center justify-center gap-2.5 text-center text-sm font-medium text-gone',
      )}
    >
      <TriangleAlert className="size-[18px] shrink-0" aria-hidden="true" />
      <p>{t('shell.activationBanner')}</p>
    </div>
  );
}
