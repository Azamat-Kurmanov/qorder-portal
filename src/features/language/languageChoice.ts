import { SUPPORTED_LANGUAGES, type Language } from '../../i18n';

/**
 * Ключ хранит не язык, а ОТВЕТ на вопрос о языке.
 *
 * Сам язык хранит детектор i18next — в `i18nextLng`, и второго источника
 * истины заводить нельзя: разойдись они, кабинет открылся бы на одном языке,
 * а помнил бы другой.
 *
 * Спрашивать по `i18nextLng` нельзя тем более: детектор пишет туда язык,
 * угаданный по браузеру, ещё до того, как человека о чём-то спросили, и
 * по нему «спрашивали или нет» не отличить. Отсюда отдельный ключ: он
 * появляется ровно в тот момент, когда человек ответил, — выбрав язык
 * или закрыв окно, что тоже ответ («оставьте как есть»).
 */
const KEY = 'q-order.portal.language-chosen';

/**
 * Хранилище может не работать — и это не повод не открыть кабинет.
 *
 * В приватном окне и при запрещённых данных сайта обращение к `localStorage`
 * бросает исключение на самом доступе к свойству, а не на чтении. Тогда
 * вопрос о языке задаётся каждый заход: помнить ответ негде. Это хуже, чем
 * помнить, но лучше, чем белый экран вместо витрины.
 */
function storage(): Storage | null {
  try {
    return window.localStorage;
  } catch {
    return null;
  }
}

/** Отвечал ли человек на вопрос о языке в этом браузере. */
export function languageChosen(): boolean {
  try {
    const stored = storage()?.getItem(KEY);
    return (SUPPORTED_LANGUAGES as readonly string[]).includes(stored ?? '');
  } catch {
    return false;
  }
}

/**
 * Запомнить ответ.
 *
 * Пишется код языка, а не «да»: на глаз в хранилище браузера видно, что
 * именно человек выбрал, а разбор чужого значения всё равно упирается
 * в проверку по списку поддерживаемых.
 */
export function rememberLanguageChoice(language: Language): void {
  try {
    storage()?.setItem(KEY, language);
  } catch {
    // Записать некуда — спросим в следующий раз. См. `storage`.
  }
}
