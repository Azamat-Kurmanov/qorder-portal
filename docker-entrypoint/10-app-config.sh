#!/bin/sh
# Настройки стенда в статику: из переменных окружения пода — в /config.js.
#
# Образ собирается без единого адреса, поэтому этот скрипт — единственное
# место, где стенд сообщает приложению, куда ходить. Каталог
# /docker-entrypoint.d/ штатно исполняется образом nginx перед запуском
# сервера, так что файл появляется до первого запроса.
#
# Чистый POSIX sh: в alpine /bin/sh — это busybox, массивов, `local`
# и подстановок вида ${x^^} там нет.
set -eu

TARGET=/usr/share/nginx/html/config.js

# Значение попадает в строковый литерал JavaScript. Кавычка или обратная
# косая черта внутри него оборвала бы литерал, и config.js стал бы
# синтаксической ошибкой — приложение встретило бы человека белым экраном
# без единого слова о причине. Порядок замен важен: сначала косая черта,
# иначе экранирующая косая из второй замены была бы экранирована повторно.
escape() {
  printf '%s' "${1:-}" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

# Отказ при старте вместо белого экрана в момент входа. Под с незаданным
# Keycloak выглядит здоровым: страница открывается, метки готовности зелёные,
# и о поломке узнают, только когда человек нажмёт «Войти». Здесь контейнер
# не запускается вовсе, и причина стоит первой строкой в его логе.
#
# Список обязательных переменных остаётся именно списком, в отличие от самой
# генерации ниже. Это не непоследовательность: «какие ключи вообще есть»
# знает ConfigMap стенда, а «без каких ключей приложение бессмысленно» знает
# только это приложение, и вывести второе из первого нельзя.
require() {
  if [ -z "${2:-}" ]; then
    echo "config: переменная $1 не задана — без неё вход в приложение невозможен" >&2
    exit 1
  fi
}

require APP_KEYCLOAK_URL "${APP_KEYCLOAK_URL:-}"
require APP_KEYCLOAK_REALM "${APP_KEYCLOAK_REALM:-}"
require APP_KEYCLOAK_CLIENT_ID "${APP_KEYCLOAK_CLIENT_ID:-}"

# APP_API_URL в проверку не входит: пустое значение здесь законно и означает
# «свой origin» — запросы уходят на /api/… той же страницы, а их проксирует
# nginx этого же контейнера.

# Генерация обходом данных, а не списком ключей.
#
# Раньше здесь стоял heredoc с четырьмя вписанными вручную ключами. Цена
# такого списка — забытая строка: ключ добавили в ConfigMap, в heredoc
# дописать забыли, и приложение получает undefined в ссылке при зелёных
# метках готовности и без единой ошибки где бы то ни было. Эта же работа
# предстоит приложениям front (там добавится APP_PORTAL_URL) и portal
# (там ещё три ключа) — то есть ошибиться предлагается трижды.
#
# Обход окружения убирает саму возможность расхождения: что положили
# в ConfigMap с префиксом APP_, то и доедет до приложения, а скрипт
# становится одним и тем же для всех трёх приложений.
#
# Префикс APP_ — это и есть граница: TZ (часовой пояс контейнера) и NGINX_*
# (адрес апстрима для прокси) относятся к контейнеру, а не к приложению,
# и в config.js им делать нечего.

# Имена берутся не из окружения вслепую, а отбираются шаблоном: имя
# переменной становится ключом объекта JavaScript, и что-нибудь вроде
# `APP_X=1; BADNAME` в окружении не должно иметь шанса дописать в файл
# произвольный текст. Пропускаются только APP_ плюс заглавные латинские
# буквы, цифры и подчёркивание.
#
# Из `env` берутся ТОЛЬКО имена: значение переменной может содержать перевод
# строки, и разбирать его построчно нельзя. Само значение читается уже
# подстановкой оболочки, которая переводов строки не боится.
names=$(env | sed -n 's/^\(APP_[A-Z0-9_]*\)=.*/\1/p' | sort -u)

# Файл собирается целиком в переменной и пишется одной операцией: частично
# записанный config.js — это опять белый экран, а `set -e` посреди heredoc
# оставил бы именно его.
body=""
for name in $names; do
  # Снимаем префикс: в объекте приложения ключи живут без него
  # (APP_KEYCLOAK_URL → KEYCLOAK_URL), как их и читает src/config.ts.
  key=${name#APP_}

  # eval — единственный способ получить значение переменной по её имени
  # в POSIX sh (косвенного ${!name} тут нет). Безопасно ровно потому, что
  # имя уже прошло отбор шаблоном выше, а значение не раскрывается повторно:
  # подставляется только имя.
  eval "value=\${$name:-}"
  value=$(escape "$value")

  # Запятая ставится перед элементом, а не после: так последний элемент
  # остаётся без висящей запятой, и файл разбирается даже самым строгим
  # парсером.
  if [ -n "$body" ]; then
    body="$body,"
  fi
  body="$body
  \"$key\": \"$value\""
done

printf 'window.__APP_CONFIG__ = {%s\n};\n' "$body" > "$TARGET"

echo "config: записан $TARGET для realm ${APP_KEYCLOAK_REALM}"
